"""
Сравнение lock-файлов pip-compile по пинам «имя==версия», а не по тексту.

Зачем: job Lint проверяет, что requirements.txt и requirements-dev.txt соответствуют *.in.
Побайтовое сравнение с пересобранным файлом ломается без настоящего расхождения: шапка
(«autogenerated by pip-compile …», команда) и пометки «# via» зависят от версии pip-tools,
а Dependabot пересобирает lock-файлы своей версией pip-tools (dependabot-core, python/helpers)
и возвращает исходную шапку. Значимо только дерево версий — его и сравниваем.

Что учитывается: строки вида «имя==версия». Имена нормализуются по PEP 503 (нижний регистр,
[-_.]+ → «-»): «PyYAML» и «pyyaml» — один пакет. Пустые строки и комментарии (шапка, «# via»)
пропускаются. Любая другая строка (опция pip, маркер окружения, пин не через «==», повтор
пакета) — ошибка разбора: молча пропущенная строка спрятала бы расхождение.

Запуск — два файла или два каталога (в каталогах сравниваются все requirements*.txt):
    python scripts/compare_lock_pins.py requirements.txt /tmp/x/requirements.txt
    python scripts/compare_lock_pins.py . /tmp/x
Первый аргумент — закоммиченное, второй — пересобранное.

Коды выхода: 0 — пины совпадают; 1 — есть расхождения (печатаются по каждому файлу);
2 — ошибка запуска или разбора (нет файла, непонятная строка, файлы в каталогах не совпадают по составу).
"""

import re
import sys
from pathlib import Path

# Пин без маркеров и хэшей: lock-файлы проекта собираются для одной платформы и без --generate-hashes
PIN_RE = re.compile(r"^(?P<name>[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?)==(?P<version>[^\s;#]+)$")
LOCK_GLOB = "requirements*.txt"


class LockParseError(Exception):
    """Lock-файл нельзя разобрать однозначно."""


def normalize(name: str) -> str:
    """Имя пакета по PEP 503."""
    return re.sub(r"[-_.]+", "-", name).lower()


def read_pins(path: Path) -> dict[str, str]:
    """Пины файла: нормализованное имя → версия."""
    pins: dict[str, str] = {}
    for number, raw in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        match = PIN_RE.match(line)
        if match is None:
            raise LockParseError(f"{path}:{number}: строка не похожа на пин «имя==версия»: {raw!r}")
        name = normalize(match["name"])
        if name in pins:
            raise LockParseError(f"{path}:{number}: пакет {name} закреплён повторно")
        pins[name] = match["version"]
    return pins


def diff_pins(committed: dict[str, str], fresh: dict[str, str]) -> list[str]:
    """Расхождения в читаемом виде; пустой список — пины совпадают."""
    lines = [f"  + {name}=={fresh[name]}  (появится после пересборки)" for name in sorted(fresh.keys() - committed)]
    lines += [
        f"  - {name}=={committed[name]}  (исчезнет после пересборки)" for name in sorted(committed.keys() - fresh)
    ]
    lines += [
        f"  ~ {name}: {committed[name]} -> {fresh[name]}"
        for name in sorted(committed.keys() & fresh)
        if committed[name] != fresh[name]
    ]
    return lines


def file_pairs(committed: Path, fresh: Path) -> list[tuple[Path, Path]]:
    """Пары файлов для сравнения: два файла или одноимённые requirements*.txt двух каталогов."""
    if committed.is_file() and fresh.is_file():
        return [(committed, fresh)]
    if committed.is_dir() and fresh.is_dir():
        committed_names = {p.name for p in committed.glob(LOCK_GLOB)}
        fresh_names = {p.name for p in fresh.glob(LOCK_GLOB)}
        if not committed_names:
            raise LockParseError(f"в каталоге {committed} нет файлов {LOCK_GLOB}")
        if committed_names != fresh_names:
            raise LockParseError(
                f"состав lock-файлов не совпадает: {committed} — {sorted(committed_names)}, "
                f"{fresh} — {sorted(fresh_names)}"
            )
        return [(committed / name, fresh / name) for name in sorted(committed_names)]
    raise LockParseError(f"нужны два существующих файла или два каталога: {committed}, {fresh}")


def main(argv: list[str]) -> int:
    if len(argv) != 2:
        print("Использование: python scripts/compare_lock_pins.py <закоммиченное> <пересобранное>", file=sys.stderr)
        return 2
    try:
        pairs = file_pairs(Path(argv[0]), Path(argv[1]))
        report = [(c, diff_pins(read_pins(c), read_pins(f))) for c, f in pairs]
    except (LockParseError, OSError) as error:
        print(f"❌ {error}", file=sys.stderr)
        return 2

    differing = [(path, lines) for path, lines in report if lines]
    for path, lines in differing:
        print(f"❌ {path.name}: пины не соответствуют исходнику")
        print("\n".join(lines))
    if differing:
        return 1
    print(f"✅ Пины совпадают: {', '.join(path.name for path, _ in report)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
