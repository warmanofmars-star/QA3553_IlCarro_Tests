"""
Проверка предусловий теста.

Зачем отдельно от assert. В тесте бывают два вида проверок:
  * ПРОВЕРКА — то, ради чего тест написан ("повторное удаление возвращает 404").
    Её провал = найден дефект. Пишется обычным assert.
  * ПРЕДУСЛОВИЕ — подготовка ("пользователь зарегистрировался", "машина создалась").
    Её провал = сломано окружение или сам тест, а не найден дефект.

Разница становится критичной с известными багами: маркеры known_bug() и observation() переводят
в xfail только AssertionError. Если предусловие проверять через assert, то при упавшем бэкенде
тест молча станет "ожидаемо упавшим из-за бага", хотя баг тут ни при чём.
require() бросает PreconditionError — и такой тест честно краснеет.
"""


class PreconditionError(Exception):
    """Тест не смог подготовить данные. Это не дефект приложения, а проблема окружения или теста."""


def require(condition: bool, message: str) -> None:
    """Аналог assert для предусловий: при нарушении бросает PreconditionError."""
    if not condition:
        raise PreconditionError(message)
