"""
Правило отображения цены в интерфейсе.

Источник — REQ-UI-SEARCH-05 (docs/requirements/requirements.md): цена на карточке показывается
с одним знаком после запятой. Во фронтенде это toFixed(1) в модуле `default`; подтверждено
исследованием Q-UI-12 (99.5 → «99.5», 250 → «250.0», 1234.56 → «1234.6»).

Ожидаемую строку тесты вычисляют этой функцией, а не записывают литералом: так видно, по какому
правилу она получена, и правило задано в одном месте.
"""

import re

# Формат строки цены на карточке: целая часть и ровно один знак после точки
UI_PRICE_PATTERN = re.compile(r"^\d+\.\d$")


def ui_price(price_per_day: float | str) -> str:
    """Строка, которой фронтенд покажет pricePerDay (аналог JS toFixed(1))."""
    # Формат Python ".1f", как и toFixed, округляет точное двоичное значение числа
    return f"{float(price_per_day):.1f}"
