class Car:
    def __init__(self, city, make, model, year, fuel, gear, wd, doors, seats, car_class, reg_number, price, about, photo_path=None):
        self.city = city
        self.make = make
        self.model = model
        self.year = year
        self.fuel = fuel
        self.gear = gear
        self.wd = wd
        self.doors = doors
        self.seats = seats
        self.car_class = car_class
        self.reg_number = reg_number
        self.price = price
        self.about = about
        self.photo_path = photo_path